/**
 * Find the manifest for the demo currently in scope.
 *
 * The manifests are keyed by demo id (`duskline`, `briarcove`, …) but the demo
 * shell exposes its Hex theme value (`lagoon`, `cardinal`, …) via
 * `data-hex-theme`. Match on each entry's `theme` field so the lookup resolves.
 */
export function findManifestByTheme(theme: string | null): DemoBuildManifest | null {
  if (!theme) return null
  return Object.values(DEMO_MANIFESTS).find((m) => m.theme === theme) ?? null
}
