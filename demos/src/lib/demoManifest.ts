/**
 * Per-demo build manifest — structured "Built with" facts for the
 * DemoAttribution component to render. Lets each demo double as live
 * documentation for the design system without duplicating data.
 *
 * Looked up by `data-hex-theme` value (the route's deslugged demo id).
 * Falls back to a generic stack summary if the theme isn't registered.
 */

export interface DemoBuildManifest {
  /** Theme name as set on `data-hex-theme="..."` */
  theme: string
  /** Human-readable demo name */
  name: string
  /** Pages count */
  pages: number
  /** Rig components touched */
  rigComponents: string[]
  /** Fonts (display + body) */
  fonts: string[]
  /** Approximate demo source LOC (template + script in index.vue + pages/*.vue) */
  loc: number
}

